"""Grade generated plans by hand, so the LLM judge can be validated against you.

    uv run python -m eval.grade            # grade plans that have no grade yet
    uv run python -m eval.grade --n 10     # generate and grade ten
    uv run python -m eval.grade --review   # re-read what you already recorded

This is the one part of the evaluation nobody can automate. If a model produces
both the plans and the grades, the agreement number measures nothing. Your
scores are the ground truth the judge is checked against.

Grade what you see, not what you hope for. A 3 is a perfectly good score.
"""

from __future__ import annotations

import argparse
import textwrap

from backend.graph import plan_trip
from backend.llm import LLM
from eval.dataset import (
    ROUTING_CASES,
    HumanGrade,
    load_human_grades,
    save_human_grades,
)
from eval.judge import RUBRIC

BAR = "─" * 72

#: Cases worth grading: enough variety that the judge is tested on more than
#: one shape of request.
GRADE_CASE_IDS = (
    "full-japan", "trip-no-flights-porto", "itinerary-kyoto",
    "stay-and-see-athens", "sights-lisbon", "weekend-barcelona",
    "honeymoon-greece", "flights-and-hotel-reykjavik", "trip-no-hotel-oslo",
    "hotels-only-paris",
)


def _ask_score(dimension: str, question: str) -> int:
    print(f"\n  {dimension.upper()}")
    for line in textwrap.wrap(question, 68):
        print(f"    {line}")
    while True:
        raw = input("    score 1-5 (or 's' to skip this plan): ").strip().lower()
        if raw == "s":
            raise KeyboardInterrupt
        if raw in {"1", "2", "3", "4", "5"}:
            return int(raw)
        print("    enter a number from 1 to 5")


def review(grades: list[HumanGrade]) -> None:
    if not grades:
        print("No grades recorded yet.")
        return
    print(f"\n{len(grades)} graded plan(s):\n")
    for grade in grades:
        detail = "  ".join(f"{k[:4]} {v}" for k, v in grade.scores.items())
        print(f"  {grade.case_id:<28} {grade.overall:>4.1f}/5   {detail}")
        if grade.note:
            print(f"    note: {grade.note}")
    print()


def main() -> int:
    parser = argparse.ArgumentParser(description="Grade plans by hand.")
    parser.add_argument("--n", type=int, default=5, help="how many plans to grade")
    parser.add_argument("--provider", default=None, help="anthropic | groq | mock")
    parser.add_argument("--review", action="store_true", help="show recorded grades and exit")
    args = parser.parse_args()

    grades = load_human_grades()
    if args.review:
        review(grades)
        return 0

    done = {g.case_id for g in grades}
    todo = [c for c in ROUTING_CASES if c.id in GRADE_CASE_IDS and c.id not in done][: args.n]

    if not todo:
        print(f"Nothing left to grade — {len(grades)} plan(s) already recorded.")
        review(grades)
        return 0

    llm = LLM(provider=args.provider)
    print(f"{BAR}\n  Grading {len(todo)} plan(s) generated by {llm.provider}/{llm.model}")
    if llm.is_mock:
        print("  WARNING: mock plans. Grading these validates nothing — use a real model.")
    print(f"  {len(grades)} already recorded. Ctrl-C to stop; progress is saved as you go.\n{BAR}")

    for index, case in enumerate(todo, start=1):
        print(f"\n\n{BAR}\n  PLAN {index}/{len(todo)}   [{case.id}]\n{BAR}")
        print(f"\n  REQUEST: {case.request}\n")

        state = plan_trip(case.request, llm)
        plan = state.get("final_plan") or ""
        if not plan:
            print(f"  (no plan produced: {state.get('clarification') or 'unknown'}) — skipping")
            continue

        print(BAR)
        print(plan)
        print(BAR)

        try:
            scores = {d: _ask_score(d, q) for d, q in RUBRIC.items()}
            note = input("\n  one-line note (optional): ").strip()
        except (KeyboardInterrupt, EOFError):
            print("\n\n  stopped — grades so far are saved")
            break

        grades.append(HumanGrade(case_id=case.id, request=case.request,
                                 plan=plan, scores=scores, note=note))
        save_human_grades(grades)
        print(f"  recorded ({len(grades)} total)")

    save_human_grades(grades)
    print(f"\n{BAR}\n  {len(grades)} graded plan(s) saved to eval/human_grades.json")
    print("  Now run: uv run python -m eval.run\n" + BAR)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
